import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';

const license = await readFile(new URL('../node_modules/libphonenumber-js/LICENSE', import.meta.url), 'utf8');

await build({
  entryPoints: [fileURLToPath(new URL('../src/phone-number.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../assets/phone-number.js', import.meta.url)),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  banner: { js: '// Generated by scripts/build-phone.mjs from libphonenumber-js/max. Do not edit manually.\n/*! libphonenumber-js\n' + license + '\n*/' },
  legalComments: 'linked',
});
